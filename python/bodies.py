import numpy as np


class Body:
    def __init__(self, name, mass, radius, x_vec, v_vec) -> None:
        self.name = name  # string
        self.mass = mass  # units of kg
        self.radius = radius  # units of km
        self.x_vec = np.array(x_vec, dtype=float)  # units of km
        self.v_vec = np.array(v_vec, dtype=float)  # units of km/s

    def return_vec(self):
        return np.concatenate([self.x_vec, self.v_vec])

    def print_info(self):
        print(
            "Name:",
            self.name,
            "\nMass:",
            self.mass,
            "\nRadius:",
            self.radius,
            "\nPosition vector:",
            self.x_vec,
            "\nVelocity vector:",
            self.v_vec,
        )


